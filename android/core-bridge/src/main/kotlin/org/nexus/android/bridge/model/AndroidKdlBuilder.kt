package org.nexus.android.bridge.model

/**
 * Generates and validates the Android sidecar runtime KDL envelope combining user proxy/routing
 * sections with Android VpnService runtime bindings (device-fd, protect-path, control socket, state dirs).
 */
object AndroidKdlBuilder {
    fun buildRuntimeConfig(
        profile: VpnProfileConfig,
        paths: RuntimeSocketPaths,
        tunFd: Int,
    ): String {
        require(tunFd >= 3) { "Android TUN descriptor must be >= 3 (got $tunFd)" }
        paths.validatePaths()

        val protect = escapeKdlString(paths.protectSocket.absolutePath)
        val control = escapeKdlString(paths.controlSocket.absolutePath)
        val dnsBridge = escapeKdlString(paths.dnsBridgeSocket.absolutePath)
        val stateDir = escapeKdlString(paths.stateDir.absolutePath)
        val cacheDir = escapeKdlString(paths.cacheDir.absolutePath)

        val tunBlock = buildString {
            appendLine("""inbound "android-tun" type="tun" {""")
            appendLine("""    device-fd $tunFd ownership="borrow"""")
            appendLine("""    mtu ${profile.mtu}""")
            appendLine("""}""")
        }

        val stateBlock = """
            schema-version 1
            role "client"
            state {
                directory "$stateDir"
                cache-directory "$cacheDir"
            }
            control socket="$control"
            // Android non-root sidecar hooks (protect_path & local DNS bridge)
            // protect-path "$protect"
            // dns-bridge-path "$dnsBridge"
            // memory-budget-mib ${profile.memoryBudgetMiB}
        """.trimIndent()

        val userBody = profile.userKdlConfig.trim()
        return buildString {
            appendLine("// Auto-generated by Nexus Android (:core-bridge)")
            appendLine(stateBlock)
            appendLine()
            append(tunBlock)
            if (userBody.isNotEmpty()) {
                appendLine()
                appendLine(userBody)
            }
        }
    }

    fun defaultSampleUserKdl(): String = """
        log {
            level "info"
            privacy "redacted"
        }

        outbound "direct" type="direct"
        outbound "block" type="block"

        routing {
            default-outbound "direct"
        }
    """.trimIndent()

    internal fun escapeKdlString(raw: String): String =
        raw.replace("\\", "\\\\").replace("\"", "\\\"")
}
