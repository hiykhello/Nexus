#!/usr/bin/env python3
"""Generate the immutable Corosio descriptor from pinned sources and patches."""

import argparse
import hashlib
from pathlib import Path
import subprocess
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DESCRIPTOR = ROOT / "3rdparty/mcpp-index/pkgs/n/nexus.corosio-source.lua"
VERSION = "0.3.12"
REVISION = "2d246de82c62a62d0da9c1e4c81a1865be7f9321"
SHA256 = "84dc5a40d7bb9ced5bd9533652fe233cf6d4b574fe66d2333f58b2f6d4002336"
SOURCE_ROOT = f"corosio-{REVISION}"
HEADERS = (
    "boost/corosio/detail/thread_local_ptr.hpp",
    "boost/corosio/native/detail/uring/uring_types.hpp",
)
PATCHES = (
    ("thread_local_modules.patch", "b1d7a479d8e34c9e7701f54dfa9e62ec425efc300a58cdcfbefa3f2b5f8fbdbf"),
    ("empty_datagram.patch", "5e3f1a7a86169a45273759cde0ec8b48d22aef53b167a5ace0d6a19937b8901d"),
)


def digest(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def patched_files(archive: Path) -> tuple[dict[str, bytes], list[str]]:
    if digest(archive) != SHA256:
        raise ValueError("Corosio archive does not match the pinned SHA-256")
    inputs = ["include/" + header for header in HEADERS]
    with tempfile.TemporaryDirectory(prefix="nexus-corosio-descriptor-") as temporary:
        directory = Path(temporary)
        with tarfile.open(archive, "r:*") as source:
            sources = sorted(member.name.removeprefix(SOURCE_ROOT + "/")
                             for member in source.getmembers()
                             if member.isfile() and member.name.startswith(SOURCE_ROOT + "/src/corosio/src/")
                             and member.name.endswith(".cpp"))
            if len(set(sources)) != len(sources):
                raise ValueError("Corosio source list has duplicates")
            for name in inputs:
                stream = source.extractfile(SOURCE_ROOT + "/" + name)
                if stream is None:
                    raise ValueError("missing Corosio input: " + name)
                with stream:
                    data = stream.read().replace(b"\r\n", b"\n")
                destination = directory / name
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(data)
        for name, expected in PATCHES:
            patch = ROOT / "3rdparty/patches/corosio" / name
            if digest(patch) != expected:
                raise ValueError("Corosio patch hash differs: " + name)
            subprocess.run(["patch", "--batch", "--forward", "--fuzz=0", "-p1", "-i", str(patch)],
                           cwd=directory, check=True, capture_output=True)
        generated = {"mcpp_generated/include/" + header: (directory / "include" / header).read_bytes()
                     for header in HEADERS}
    return generated, sources


def descriptor(archive: Path) -> str:
    _, sources = patched_files(archive)
    entries = "\n".join(f'      "*/{name}",' for name in sources)
    return f'''-- Generated by scripts/mcpp-corosio-sources.py; do not edit.
package = {{
  spec = "1", namespace = "nexus", name = "corosio-source", licenses = {{ "BSL-1.0" }},
  description = "Pinned upstream source for Nexus", repo = "https://github.com/cppalliance/corosio", type = "package",
  xpm = {{ linux = {{ ["{VERSION}"] = {{ url = "https://github.com/cppalliance/corosio/archive/{REVISION}.tar.gz", sha256 = "{SHA256}" }} }} }},
  mcpp = {{ language = "c++23", import_std = false,
    include_dirs = {{ "*/include", "*/src/corosio" }},
    private_include_dirs = {{ "*/src/corosio" }},
    sources = {{
{entries}
    }},
    defines = {{ "BOOST_COROSIO_NO_LIB", "BOOST_COROSIO_STATIC_LINK" }},
    cxxflags = {{ "-DBOOST_COROSIO_SOURCE", "-fno-modules" }}, ldflags = {{ "-lpthread" }},
    features = {{ ["uring"] = {{ defines = {{ "BOOST_COROSIO_HAVE_LIBURING=1" }}, requires = {{ "nexus-system-liburing" }} }} }},
    targets = {{ ["corosio"] = {{ kind = "lib" }} }}, deps = {{}},
  }},
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = descriptor(args.archive)
    if args.write:
        DESCRIPTOR.write_text(expected)
    elif DESCRIPTOR.read_text() != expected:
        raise ValueError("Corosio descriptor differs from pinned sources and patches")
    print(f"Corosio mcpp descriptor matches {VERSION}")


if __name__ == "__main__":
    main()
