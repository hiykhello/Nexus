#!/usr/bin/env python3
"""Generate compact C++26 #embed dashboard assets from web/dist into src/control_api/."""
from __future__ import annotations

import argparse
import gzip
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_DIST = ROOT / "web" / "dist"
DEFAULT_OUT = ROOT / "src" / "control_api"

MIME_TYPES: dict[str, str] = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".json": "application/json; charset=utf-8",
    ".webmanifest": "application/json; charset=utf-8",
    ".woff2": "font/woff2",
    ".txt": "text/plain; charset=utf-8",
}

COMPRESSIBLE_EXTS = {".js", ".mjs", ".css", ".svg", ".json", ".webmanifest", ".txt"}
MIN_GZIP_BYTES = 2048


def c_escape(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def safe_asset_filename(rel_posix: str, gzipped: bool) -> str:
    flat = re.sub(r"[^A-Za-z0-9._-]", "_", rel_posix.replace("/", "__"))
    return flat + ".gz" if gzipped else flat


def collect_assets(dist_dir: pathlib.Path) -> list[tuple[str, str, bytes, bool, bool]]:
    if not dist_dir.is_dir():
        raise SystemExit(f"ERROR: web dist directory not found: {dist_dir}")
    entries: list[tuple[str, str, bytes, bool, bool]] = []
    for path in sorted(dist_dir.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(dist_dir)
        if any(part.startswith(".") for part in rel.parts):
            continue
        ext = path.suffix.lower()
        mime = MIME_TYPES.get(ext)
        if not mime:
            continue
        rel_posix = rel.as_posix()
        raw = path.read_bytes()
        gzipped = False
        payload = raw
        if rel_posix != "index.html" and ext in COMPRESSIBLE_EXTS and len(raw) >= MIN_GZIP_BYTES:
            compressed = gzip.compress(raw, compresslevel=9, mtime=0)
            if len(compressed) < len(raw):
                payload = compressed
                gzipped = True
        immutable = rel_posix.startswith("assets/")
        entries.append((f"/{rel_posix}", mime, payload, gzipped, immutable))

    if not any(route == "/index.html" for route, *_ in entries):
        raise SystemExit(f"ERROR: {dist_dir / 'index.html'} is required")
    return entries


def render_inc(entries: list[tuple[str, str, bytes, bool, bool]]) -> tuple[str, dict[str, bytes]]:
    lines = [
        "// Generated by scripts/embed-web-dashboard.py from web/dist — do not edit manually.",
        "#include <cstddef>",
        "#if defined(__clang__)",
        "#pragma clang diagnostic push",
        '#pragma clang diagnostic ignored "-Wc23-extensions"',
        "#endif",
        "namespace control_api::embedded_dashboard_raw {",
        "    struct Entry {",
        "        char const* route;",
        "        char const* mime;",
        "        unsigned char const* data;",
        "        std::size_t size;",
        "        bool gzipped;",
        "        bool immutable;",
        "    };",
    ]
    files: dict[str, bytes] = {}
    table_rows: list[str] = []
    for idx, (route, mime, payload, gzipped, immutable) in enumerate(entries):
        fname = safe_asset_filename(route.lstrip("/"), gzipped)
        files[fname] = payload
        lines.append(f"    inline constexpr unsigned char kAsset_{idx}[] = {{")
        lines.append(f'#embed "embedded_assets/{fname}"')
        lines.append("    };")
        table_rows.append(
            f"        {{{c_escape(route)}, {c_escape(mime)}, kAsset_{idx}, "
            f"sizeof(kAsset_{idx}), {'true' if gzipped else 'false'}, "
            f"{'true' if immutable else 'false'}}},"
        )
    lines.append("    inline constexpr Entry kEntries[] = {")
    lines.extend(table_rows)
    lines.append("    };")
    lines.append("    inline constexpr std::size_t kEntryCount = sizeof(kEntries) / sizeof(kEntries[0]);")
    lines.append("}")
    lines.append("#if defined(__clang__)")
    lines.append("#pragma clang diagnostic pop")
    lines.append("#endif")
    return "\n".join(lines) + "\n", files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dist", type=pathlib.Path, default=DEFAULT_DIST)
    parser.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="Verify generated files match web/dist")
    args = parser.parse_args()

    entries = collect_assets(args.dist)
    inc_text, asset_files = render_inc(entries)
    inc_path = args.out / "embedded_dashboard_assets.inc"
    assets_dir = args.out / "embedded_assets"

    if args.check:
        if not inc_path.is_file() or inc_path.read_text(encoding="utf-8") != inc_text:
            print("FAIL: embedded_dashboard_assets.inc is out of sync with web/dist", file=sys.stderr)
            return 1
        existing = {p.name for p in assets_dir.iterdir() if p.is_file()} if assets_dir.is_dir() else set()
        if existing != set(asset_files.keys()):
            print("FAIL: embedded_assets file list is out of sync with web/dist", file=sys.stderr)
            return 1
        for name, expected in asset_files.items():
            if (assets_dir / name).read_bytes() != expected:
                print(f"FAIL: embedded_assets/{name} content mismatch", file=sys.stderr)
                return 1
        print(f"OK: {len(entries)} embedded dashboard assets are in sync")
        return 0

    assets_dir.mkdir(parents=True, exist_ok=True)
    for stale in assets_dir.iterdir():
        if stale.is_file() and stale.name not in asset_files:
            stale.unlink()
    for name, payload in asset_files.items():
        (assets_dir / name).write_bytes(payload)
    inc_path.write_text(inc_text, encoding="utf-8")

    total = sum(len(b) for b in asset_files.values())
    print(f"Embedded {len(entries)} assets ({total} bytes total) into {assets_dir}")
    for route, mime, payload, gzipped, _ in entries:
        enc = "gzip" if gzipped else "raw"
        print(f"  {route} -> {len(payload)} bytes ({enc}, {mime})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
