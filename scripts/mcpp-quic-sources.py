#!/usr/bin/env python3
"""Generate/check the pinned Linux ngtcp2 and nghttp3 C-core descriptors.

No network access or CMake execution is needed. The configuration macros were
measured with the upstream lib-only CMake build on Linux x86-64 glibc. Only the
upstream lib source list is compiled; no crypto/TLS helper enters either core.
"""

import argparse
import hashlib
from pathlib import Path, PurePosixPath
import re
import tarfile

ROOT = Path(__file__).resolve().parents[1]
PINS = {
    "ngtcp2": ("1.26.0", "7804aa0fa1c39942ba322a90805824c37231f7675b08d0c3cc4332858a7b085e"),
    "nghttp3": ("1.19.0", "228e17f5cc3d4de7bfced9912bd09de30e7f45741cc47503cf88d3fa9209e155"),
}
# Recipe revisions are immutable install identities. Upstream release numbers
# remain in URLs, source roots and PINS; earlier development installs survive.
PACKAGE_VERSIONS = {"ngtcp2": "1.26.0-nexus.1", "nghttp3": "1.19.0-nexus.1"}
CONFIG = {
    "ngtcp2": {
        "HAVE_ARPA_INET_H": "1", "HAVE_NETINET_IN_H": "1", "HAVE_NETINET_IP_H": "1",
        "HAVE_UNISTD_H": "1", "HAVE_ENDIAN_H": "1", "HAVE_BYTESWAP_H": "1",
        "HAVE_ASM_TYPES_H": "1", "HAVE_LINUX_NETLINK_H": "1", "HAVE_LINUX_RTNETLINK_H": "1",
        "HAVE_DECL_BE64TOH": "1", "HAVE_DECL_BSWAP_64": "1", "HAVE_EXPLICIT_BZERO": "1",
    },
    "nghttp3": {
        "HAVE_ARPA_INET_H": "1", "HAVE_UNISTD_H": "1", "HAVE_ENDIAN_H": "1",
        "HAVE_BYTESWAP_H": "1", "HAVE_DECL_BE64TOH": "1", "HAVE_DECL_BSWAP_64": "1",
    },
}


def descriptor(name: str, archive: Path) -> str:
    version, digest = PINS[name]
    with archive.open("rb") as source:
        actual = hashlib.file_digest(source, "sha256").hexdigest()
    if actual != digest:
        raise ValueError(f"{archive}: SHA-256 {actual}, expected {digest}")
    prefix = f"{name}-{version}/"
    with tarfile.open(archive, "r:xz") as tar:
        cmake = tar.extractfile(prefix + "lib/CMakeLists.txt").read().decode()
        lists = re.findall(rf"set\(\s*{name}_SOURCES\s+(.*?)\)", cmake, re.S)
        if len(lists) != 1:
            raise ValueError(f"{name}: expected one upstream lib source list")
        sources = lists[0].split()
        if len(sources) != len(set(sources)):
            raise ValueError(f"{name}: duplicate source")
        for item in sources:
            path = PurePosixPath(item)
            if path.is_absolute() or ".." in path.parts or path.suffix != ".c":
                raise ValueError(f"{name}: invalid C-core source {item!r}")
            tar.getmember(prefix + "lib/" + item)
        header = tar.extractfile(prefix + f"lib/includes/{name}/version.h").read().decode()
        if f'#define {name.upper()}_VERSION "{version}"' not in header:
            raise ValueError(f"{name}: release header version mismatch")
        private_symbols = []
        if name == "nghttp3":
            helper = tar.extractfile(prefix + "lib/sfparse/sfparse.h").read().decode()
            private_symbols = re.findall(r"^(?:void|int)\s+(sfparse_\w+)\s*\(", helper, re.M)
            if len(private_symbols) != 9 or len(set(private_symbols)) != 9:
                raise ValueError("nghttp3: bundled sfparse public function set changed")
    entries = "\n".join(f'      "*/lib/{item}",' for item in sources)
    macros = "\n".join(f"#define {key} {value}" for key, value in CONFIG[name].items())
    upper = name.upper()
    definitions = ["HAVE_CONFIG_H", f"BUILDING_{upper}", f"{upper}_STATICLIB"]
    # mcpp links package objects directly. Keep this bundled helper private so
    # HTTP/2's independent sfparse copy can coexist in the same binary.
    definitions += [f"{symbol}=nexus_nghttp3_{symbol}" for symbol in private_symbols]
    definitions = ", ".join(f'"{value}"' for value in definitions)
    return f'''-- Generated by scripts/mcpp-quic-sources.py from the pinned release.
-- Linux x86-64 glibc, upstream C core only; no TLS or crypto helper.
package = {{
  spec = "1", namespace = "nexus", name = "{name}-source",
  description = "Pinned {name} C core", licenses = {{ "MIT" }},
  repo = "https://github.com/ngtcp2/{name}", type = "package",
  archs = {{ "x86_64" }},
  xpm = {{ linux = {{ ["{PACKAGE_VERSIONS[name]}"] = {{
    url = "https://github.com/ngtcp2/{name}/releases/download/v{version}/{name}-{version}.tar.xz",
    sha256 = "{digest}",
  }} }} }},
  mcpp = {{ language = "c++23", c_standard = "gnu11", import_std = false,
    generated_files = {{ ["mcpp_generated/config.h"] = [==[
#ifndef NEXUS_{upper}_MCPP_CONFIG_H
#define NEXUS_{upper}_MCPP_CONFIG_H
{macros}
#endif
]==] }},
    include_dirs = {{ "mcpp_generated", "*/lib/includes" }},
    private_include_dirs = {{ "mcpp_generated" }},
    defines = {{ {definitions} }},
    sources = {{
{entries}
    }},
    targets = {{ ["{name}-source"] = {{ kind = "lib" }} }}, deps = {{}},
  }},
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("name", choices=PINS)
    parser.add_argument("archive", type=Path)
    parser.add_argument("--cmake-config", type=Path, help="compare upstream generated config.h macros")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    if args.cmake_config:
        actual = dict(re.findall(r"^#define\s+(\w+)\s+(.+?)\s*$", args.cmake_config.read_text(), re.M))
        if actual != CONFIG[args.name]:
            raise ValueError(f"{args.name}: CMake configuration changed: {actual!r}")
    output = ROOT / f"3rdparty/mcpp-index/pkgs/n/nexus.{args.name}-source.lua"
    expected = descriptor(args.name, args.archive)
    if args.write:
        output.write_text(expected)
    elif output.read_text() != expected:
        raise ValueError(f"{output}: stale descriptor")
    print(f"{args.name} C-core descriptor matches pinned upstream release")


if __name__ == "__main__":
    main()
