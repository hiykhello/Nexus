#!/usr/bin/env python3
"""Generate/check the Linux host nghttp2 descriptor from the pinned release.

The caller supplies the release archive; this script does not download it.
The config values are the result of the original recipe's lib-only CMake
configuration on the documented x86-64 Linux host and system root. Pass the
resulting config.h with --cmake-config to compare the defined macros again.
"""

import argparse
import hashlib
from pathlib import Path
import re
import tarfile

ROOT = Path(__file__).resolve().parents[1]
VERSION = "1.71.0"
SHA256 = "c0f55121d88650e4b9227aec28cebaf664d2417ca60fe70be0f8d38829f52116"
DESCRIPTOR = ROOT / "3rdparty/mcpp-index/pkgs/n/nexus.nghttp2-source.lua"
CONFIG = {
    "NGHTTP2_NORETURN": "__attribute__((noreturn))",
    "HAVE__EXIT": "1",
    "HAVE_ACCEPT4": "1",
    "HAVE_CLOCK_GETTIME": "1",
    "HAVE_MKOSTEMP": "1",
    "HAVE_PIPE2": "1",
    "HAVE_DECL_INITGROUPS": "1",
    "HAVE_DECL_CLOCK_MONOTONIC": "1",
    "NOTHREADS": "1",
    "HAVE_ARPA_INET_H": "1",
    "HAVE_FCNTL_H": "1",
    "HAVE_INTTYPES_H": "1",
    "HAVE_LIMITS_H": "1",
    "HAVE_NETDB_H": "1",
    "HAVE_NETINET_IN_H": "1",
    "HAVE_NETINET_IP_H": "1",
    "HAVE_PWD_H": "1",
    "HAVE_SYS_SOCKET_H": "1",
    "HAVE_SYS_TIME_H": "1",
    "HAVE_SYSLOG_H": "1",
    "HAVE_UNISTD_H": "1",
}


def descriptor(archive: Path) -> str:
    with archive.open("rb") as source:
        digest = hashlib.file_digest(source, "sha256").hexdigest()
    if digest != SHA256:
        raise ValueError(f"{archive}: SHA-256 {digest}, expected {SHA256}")
    with tarfile.open(archive, "r:xz") as tar:
        member = tar.extractfile(f"nghttp2-{VERSION}/lib/CMakeLists.txt")
        if member is None:
            raise ValueError("pinned archive has no lib/CMakeLists.txt")
        cmake = member.read().decode("utf-8")
        matches = re.findall(r"set\(\s*NGHTTP2_SOURCES\s+(.*?)\)", cmake, re.S)
        if len(matches) != 1:
            raise ValueError("expected one upstream NGHTTP2_SOURCES list")
        sources = matches[0].split()
        for source in sources:
            path = Path(source)
            if path.name != source or path.suffix != ".c":
                raise ValueError(f"unexpected nghttp2 source {source!r}")
            tar.getmember(f"nghttp2-{VERSION}/lib/{source}")
        tar.getmember(f"nghttp2-{VERSION}/lib/includes/nghttp2/nghttp2ver.h")
    if len(sources) != len(set(sources)):
        raise ValueError("upstream source list contains duplicates")
    entries = "\n".join(f'      "*/lib/{source}",' for source in sources)
    defines = "\n".join([
        "#define NOTHREADS 1",
        "#if defined(_WIN32)",
        "#define NGHTTP2_NORETURN __declspec(noreturn)",
        "#define HAVE_WINDOWS_H 1",
        "#define HAVE_GETTICKCOUNT64 1",
        "#else",
        "#define NGHTTP2_NORETURN __attribute__((noreturn))",
        "#define HAVE__EXIT 1",
        "#define HAVE_CLOCK_GETTIME 1",
        "#define HAVE_DECL_CLOCK_MONOTONIC 1",
        "#define HAVE_DECL_INITGROUPS 1",
        "#define HAVE_ARPA_INET_H 1",
        "#define HAVE_FCNTL_H 1",
        "#define HAVE_INTTYPES_H 1",
        "#define HAVE_LIMITS_H 1",
        "#define HAVE_NETDB_H 1",
        "#define HAVE_NETINET_IN_H 1",
        "#define HAVE_NETINET_IP_H 1",
        "#define HAVE_PWD_H 1",
        "#define HAVE_SYS_SOCKET_H 1",
        "#define HAVE_SYS_TIME_H 1",
        "#define HAVE_SYSLOG_H 1",
        "#define HAVE_UNISTD_H 1",
        "#if defined(__linux__)",
        "#define HAVE_ACCEPT4 1",
        "#define HAVE_MKOSTEMP 1",
        "#define HAVE_PIPE2 1",
        "#endif",
        "#endif",
    ])
    return f'''-- Generated by scripts/mcpp-nghttp2-sources.py from the pinned release.
-- Cross-platform lib-only CMake configuration (Linux / Apple / Windows).
package = {{
  spec = "1", namespace = "nexus", name = "nghttp2-source",
  description = "Pinned nghttp2 HTTP/2 core", licenses = {{ "MIT" }},
  repo = "https://github.com/nghttp2/nghttp2", type = "package",
  archs = {{ "x86_64", "arm64", "aarch64" }},
  xpm = {{ linux = {{ ["{VERSION}"] = {{
    url = "https://github.com/nghttp2/nghttp2/releases/download/v{VERSION}/nghttp2-{VERSION}.tar.xz",
    sha256 = "{SHA256}",
  }} }} }},
  mcpp = {{ language = "c++23", c_standard = "gnu23", import_std = false,
    generated_files = {{ ["mcpp_generated/config.h"] = [==[
#ifndef NEXUS_NGHTTP2_MCPP_CONFIG_H
#define NEXUS_NGHTTP2_MCPP_CONFIG_H
{defines}
#endif
]==] }},
    include_dirs = {{ "mcpp_generated", "*/lib/includes" }},
    private_include_dirs = {{ "mcpp_generated" }},
    defines = {{ "HAVE_CONFIG_H", "BUILDING_NGHTTP2", "NGHTTP2_STATICLIB" }},
    ldflags = {{ "-lpthread" }},
    sources = {{
{entries}
    }},
    targets = {{ ["nghttp2-source"] = {{ kind = "lib" }} }}, deps = {{}},
  }},
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path, help="SHA-256 pinned release archive")
    parser.add_argument("--cmake-config", type=Path, help="compare CMake's generated config.h macros")
    parser.add_argument("--write", action="store_true", help="replace the generated descriptor")
    args = parser.parse_args()
    if args.cmake_config:
        actual = dict(re.findall(r"^#define\s+(\w+)\s+(.+?)\s*$", args.cmake_config.read_text(), re.M))
        if actual != CONFIG:
            raise ValueError(f"{args.cmake_config}: CMake macros differ: {actual!r}")
    expected = descriptor(args.archive)
    if args.write:
        DESCRIPTOR.write_text(expected, encoding="utf-8")
    elif DESCRIPTOR.read_text(encoding="utf-8") != expected:
        raise ValueError(f"{DESCRIPTOR} differs from the pinned source list or configuration")
    print(f"nghttp2 mcpp descriptor matches {VERSION}")


if __name__ == "__main__":
    main()
