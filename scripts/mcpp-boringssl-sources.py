#!/usr/bin/env python3
"""Generate or check the mcpp libcrypto source list from the pinned archive.

The archive is an input supplied by the caller; this script never downloads it.
The list is the upstream non-FIPS static crypto target, including its generated
assembly sources. All platforms in the archive use the same preprocessor-guarded
assembly list; this descriptor is currently restricted to Linux x86-64.
"""

import argparse
import hashlib
from pathlib import Path
import re
import tarfile
import tempfile
import subprocess

ROOT = Path(__file__).resolve().parents[1]
VERSION = "0.1.2"
PATCHES = (
    ("3rdparty/patches/boringssl/x509_name_allocation.patch", "59a5895158eacd1ef56303d5b8264851db4be798f42bcbd3a55f0dc8caa4040f"),
    ("3rdparty/patches/boringssl/x509_pubkey_allocation_error.patch", "422ed3fb7607312cee9190200eebbec3f6c6b8f9e03db0771a21b1f2fc28e926"),
)
PATCHED_SOURCES = ("crypto/x509/x_name.cc", "crypto/x509/x_pubkey.cc")
REVISION = "e651545da6e26e1f4420723a3b69a78ed1b9c51d"
SHA256 = "8df889167a2ca2237073cfed3147ac7b2f548f7dbf3daf4928a0ae6504d2013f"
DESCRIPTOR = ROOT / "3rdparty/mcpp-index/pkgs/n/nexus.boringssl-crypto-source.lua"
GROUPS = ("BCM_SOURCES", "BCM_SOURCES_ASM", "CRYPTO_SOURCES", "CRYPTO_SOURCES_ASM")


def descriptor(archive: Path) -> str:
    with archive.open("rb") as source:
        digest = hashlib.file_digest(source, "sha256").hexdigest()
    if digest != SHA256:
        raise ValueError(f"{archive}: SHA-256 {digest}, expected {SHA256}")
    with tarfile.open(archive, "r:gz") as tar:
        member = tar.extractfile(f"boringssl-{REVISION}/gen/sources.cmake")
        if member is None:
            raise ValueError("pinned archive has no gen/sources.cmake")
        cmake = member.read().decode("utf-8")
        originals = {}
        for name in PATCHED_SOURCES:
            native = tar.extractfile(f"boringssl-{REVISION}/{name}")
            if native is None:
                raise ValueError("pinned archive has no " + name)
            originals[name] = native.read()
    with tempfile.TemporaryDirectory(prefix="nexus-boringssl-descriptor-") as temporary:
        directory = Path(temporary)
        for name, data in originals.items():
            target = directory / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        for name, expected in PATCHES:
            patch = ROOT / name
            if hashlib.sha256(patch.read_bytes()).hexdigest() != expected:
                raise ValueError("BoringSSL patch SHA-256 differs: " + name)
            subprocess.run(["patch", "--batch", "--forward", "--fuzz=0", "-p1", "-i", str(patch)],
                           cwd=directory, check=True, capture_output=True)
        patched = {name: (directory / name).read_text(encoding="utf-8") for name in PATCHED_SOURCES}
    if any("]==]" in data for data in patched.values()):
        raise ValueError("patched source contains Lua delimiter")
    sources = []
    for group in GROUPS:
        matches = re.findall(r"set\(\s*" + group + r"\s+(.*?)\)", cmake, re.S)
        if len(matches) != 1:
            raise ValueError(f"expected one upstream {group} list")
        for source in matches[0].split():
            path = Path(source)
            if path.is_absolute() or ".." in path.parts or path.suffix not in {".cc", ".S"}:
                raise ValueError(f"unexpected {group} source {source!r}")
            sources.append(source)
    if len(sources) != len(set(sources)):
        raise ValueError("upstream crypto source lists contain duplicates")
    for name in PATCHED_SOURCES:
        if sources.count(name) != 1:
            raise ValueError("replacement source does not have exactly one upstream provider")
    entries = "\n".join(f'      "*/{source}",' for source in sources)
    return f'''-- Generated by scripts/mcpp-boringssl-sources.py from BoringSSL's
-- gen/sources.cmake at {REVISION}; verify before changing the pin.
package = {{
  spec = "1", namespace = "nexus", name = "boringssl-crypto-source",
  description = "Pinned BoringSSL non-FIPS libcrypto sources", licenses = {{ "Apache-2.0" }},
  repo = "https://boringssl.googlesource.com/boringssl/", type = "package",
  archs = {{ "x86_64" }},
  xpm = {{ linux = {{ ["{VERSION}"] = {{
    url = "https://github.com/google/boringssl/archive/{REVISION}.tar.gz",
    sha256 = "{SHA256}",
  }} }} }},
  mcpp = {{ language = "c++23", import_std = false,
    include_dirs = {{ "*/include", "*/crypto/x509" }},
    private_include_dirs = {{ "*/crypto/x509" }},
    defines = {{ "BORINGSSL_IMPLEMENTATION" }},
    cxxflags = {{ "-fno-modules", "-fno-exceptions", "-fno-rtti" }},
    flags = {{ {{ glob = "**/*.S", asmflags = {{ "-Wa,--noexecstack" }} }} }},
    ldflags = {{ "-lpthread" }},
    sources = {{
{entries}
    }},
    targets = {{ ["boringssl-crypto-source"] = {{ kind = "lib" }} }}, deps = {{}},
  }},
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path, help="SHA-256 pinned BoringSSL archive")
    parser.add_argument("--write", action="store_true", help="replace the generated descriptor")
    args = parser.parse_args()
    expected = descriptor(args.archive)
    if args.write:
        DESCRIPTOR.write_text(expected, encoding="utf-8")
    elif DESCRIPTOR.read_text(encoding="utf-8") != expected:
        raise ValueError(f"{DESCRIPTOR} differs from the pinned upstream source list")
    print(f"BoringSSL mcpp descriptor matches {REVISION}")


if __name__ == "__main__":
    main()
