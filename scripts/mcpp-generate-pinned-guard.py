#!/usr/bin/env python3
"""Verify pinned archives and generate the build-time source-input guard.

Generation needs the locally cached pinned upstream archives. Normal builds
only need the checked-in guard and its embedded inputs.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
VERIFY = ROOT / "tests/mcpp_pinned_deps.py"
OUTPUT = ROOT / "src/build/mcpp_pinned_guard.cpp"
DEFAULT_CACHE = ROOT / ".mcpp/.xlings/data/runtimedir"
PINS_PATH = "3rdparty/mcpp-pins.json"
PINS = json.loads((ROOT / PINS_PATH).read_text(encoding="utf-8"))
INPUTS = [PINS_PATH]
for pin in PINS.values():
    INPUTS.append(pin["descriptor"])
    INPUTS.extend(patch["path"] for patch in pin.get("patches", []))
    if "mcpp_patch" in pin:
        INPUTS.append(pin["mcpp_patch"]["path"])
    INPUTS.extend(patch["path"] for patch in pin.get("mcpp_patches", []))
INPUTS.extend([
    "tests/mcpp_pinned_deps.py", "3rdparty/argon2/symbols.txt", "scripts/mcpp-boringssl-sources.py",
    "scripts/mcpp-nghttp2-sources.py", "scripts/mcpp-generate-pinned-guard.py",
    "scripts/mcpp-quic-sources.py", "scripts/mcpp-quic-modules.py",
    "scripts/mcpp-corosio-sources.py", "scripts/mcpp-verify-installed.py", "src/mcpp.toml",
    "3rdparty/quic-boundary.json", "3rdparty/modules/ngtcp2.cppm", "3rdparty/modules/nghttp3.cppm",
])


def verify_pins(cache: Path) -> None:
    subprocess.run([sys.executable, str(VERIFY), "--cache", str(cache)], check=True)


def fnv1a(data: bytes) -> int:
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return value


def generate() -> str:
    lines = [
        "// Generated by scripts/mcpp-generate-pinned-guard.py; do not edit.",
        "// FNV-1a detects accidental input drift; it is not a security digest.",
        "namespace {",
    ]
    for index, name in enumerate(INPUTS):
        digest = fnv1a((ROOT / name).read_bytes())
        lines.extend([
            f"consteval unsigned long long pinned_input_{index}() {{",
            "    constexpr unsigned char bytes[] = {",
            f'#embed "../../{name}"',
            "    };",
            "    unsigned long long hash = 14695981039346656037ull;",
            "    // Keep each loop below GCC's default constexpr iteration limit.",
            "    for (decltype(sizeof(bytes)) base = 0; base < sizeof(bytes); base += 16384) {",
            "        auto end = base + 16384 < sizeof(bytes) ? base + 16384 : sizeof(bytes);",
            "        for (auto i = base; i < end; ++i) hash = (hash ^ bytes[i]) * 1099511628211ull;",
            "    }",
            "    return hash;",
            "}",
            f'static_assert(pinned_input_{index}() == {digest}ull,',
            f'              "{name} changed: verify pinned archives and regenerate the mcpp guard");',
        ])
    lines.extend(["}", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=DEFAULT_CACHE,
                        help="directory containing all pinned upstream archives")
    parser.add_argument("--check", action="store_true", help="check the generated guard without writing it")
    args = parser.parse_args()
    verify_pins(args.cache)
    expected = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise ValueError(f"{OUTPUT} is stale; verify the changes and regenerate it")
        print("mcpp pinned-input guard is current")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected, encoding="utf-8")
        print(f"generated {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
